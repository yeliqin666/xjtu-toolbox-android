/** `app_guide` 的三种取法：只要功能入口、只要食堂与开放时间、或两者都给（[topic] 不认识时）。 */
fun agentGuideText(topic: String?): String = when (topic?.trim()?.lowercase()) {
    "app" -> APP_GUIDE
    "campus", "xingqing" -> XINGQING_GUIDE
    else -> APP_GUIDE + "\n\n" + XINGQING_GUIDE
}
