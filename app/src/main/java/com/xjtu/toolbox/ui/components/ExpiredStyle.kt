package com.xjtu.toolbox.ui.components

/**
 * 已结束 / 已过期条目的统一样式：考试已结束、今日时间轴上已经过去的课、没课的周，都用这一套。
 *
 * 规范是：整块内容压暗到 [CONTENT_ALPHA]，底色用 `surfaceVariant`，不用任何强调色，
 * 只对「还没发生」才有意义的信息（比如考试座位号）直接隐藏。
 *
 * 之所以抽成一个常量而不是各处自己写 alpha：以前今日时间轴写死 0.45、经典考试卡片写 0.5、
 * 别处又是 0.6，同一种「过去了」在不同页面深浅不一，看着像三种不同的状态。
 */
object ExpiredStyle {
    /** 沿用「今日」时间轴原有的压暗程度，这样今日栏的观感不变。 */
    const val CONTENT_ALPHA = 0.45f
}
