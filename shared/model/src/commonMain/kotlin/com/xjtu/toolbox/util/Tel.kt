package com.xjtu.toolbox.util

/**
 * 把接口里人写的电话串，转成 `tel:` 能拨的号码。
 *
 * 学校各处返回的电话格式并不统一：黄页里是「029-82668888」，学籍档案里可能是
 * 「138 1234 5678」或「82668888 转 801」。而 `ACTION_DIAL` 只认数字，原文整段
 * 塞进 `tel:` 会拨不出去，所以这里先做两步规整再取号。
 *
 * 取不出号码（空串、「见年级群」这类）返回空串，**调用方必须据此决定要不要把号码
 * 画成可点的蓝色**——否则只是把「点了没反应」换成「看起来能拨、其实拨不出去」。
 */
fun String.toDialableTel(): String {
    // 只抹空白，不抹「-」：「82668888-101」里的「-」后面是分机号，粘起来会拨错号码，
    // 留着反而让正则只截到正确的主号码。
    val compact = replace(WHITESPACE, "")
    // 「+86 138 1234 5678」压完是 13 位。国家码在国内拨不出去，但仅在后面正好跟一个
    // 11 位手机号时才去掉，免得误伤本就以 86 开头的号码。
    return DIGITS.find(compact.replaceFirst(COUNTRY_CODE, ""))?.value.orEmpty()
}

/** 半角与全角空白，校方数据里两种都出现过。 */
private val WHITESPACE = Regex("""[\s\u3000]+""")

/** `+86` / `86` 国家码，仅当后面正好跟一个 11 位手机号时才认。 */
private val COUNTRY_CODE = Regex("""^\+?86(?=1\d{10}$)""")

/** 第一段 7 位以上的数字：校内固话 8 位、手机 11 位，都能覆盖。 */
private val DIGITS = Regex("""\d{7,}""")
